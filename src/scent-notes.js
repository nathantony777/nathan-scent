function noteWords(n) {
  return [...(n.top || []), ...(n.heart || []), ...(n.base || []), ...(n.accords || [])];
}

export function searchableNotes(id) {
  const n = scentNotes[id];
  return n ? [...noteWords(n), ...(n.additionalSources || []).flatMap(s => s.profile ? noteWords(s.profile) : [])].join(" ") : "";
}
